import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

export function snapchatTheme() {
  const base = readFileSync(new URL('../themes/PresenceMessages.theme.css', import.meta.url), 'utf8');
  const variant = readFileSync(new URL('../themes/snapchat.variant.css', import.meta.url), 'utf8');
  return base.replace('@name Messages for Discord', '@name Snapchat for Discord')
    .replace(/@description .*/, '@description A Snapchat-inspired optional theme in Discord’s layout. Enable this theme on its own. Sender styling uses Enhanced Presence+ or Vencord ThemeAttributes.')
    .replaceAll('--ep-messages-', '--ep-snapchat-')
    .replaceAll('ep-composer-menu-in', 'ep-snapchat-composer-menu-in')
    + '\n/* Generated by npm run build:themes; edit snapchat.variant.css for this design. */\n' + variant;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  writeFileSync(new URL('../themes/PresenceSnapchat.theme.css', import.meta.url), snapchatTheme());
}
